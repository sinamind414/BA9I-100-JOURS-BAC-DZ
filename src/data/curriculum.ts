function getBranchFocusSubjects(branch: BranchId): SubjectId[] {
  const info = BRANCHES.find((b) => b.id === branch) || BRANCHES[0];
  return info.coreSubjects;
}

export function getDayPlan(dayNumber: number, branch: BranchId): DayPlan {
  const safeDay = Number.isFinite(dayNumber) ? Math.floor(dayNumber) : 1;
  const clampedDay = Math.max(1, Math.min(100, safeDay));
  const allowed = new Set(getBranchFocusSubjects(branch));
  const base = BOOK_DAYS_ALL[clampedDay];

  if (base) {
    const filteredTasks = base.tasks.filter((t) => allowed.has(t.subject));
    if (filteredTasks.length > 0) {
      return {
        ...base,
        tasks: filteredTasks,
      };
    }
    // Branch-tailored adaptation when a scientific-heavy book day has no literary/langue subject
    const subjects = getBranchFocusSubjects(branch);
    const adaptedTasks: StudyTask[] = [0, 1, 2].map((slot) => {
      const subj = subjects[(clampedDay + slot) % subjects.length];
      const pool = SYLLABUS_BLOCKS[subj];
      const topic = pool[(clampedDay + slot) % pool.length];
      return {
        id: `d${clampedDay}-${branch}-${subj}-${slot}`,
        day: clampedDay,
        subject: subj,
        title: topic,
        xp: slot === 0 ? 55 : 45,
        isSpacedCandidate: slot === 0 || subj === 'history' || subj === 'islamic' || subj === 'philosophy',
      };
    });
    return {
      ...base,
      tasks: adaptedTasks,
    };
  }

  const subjects = getBranchFocusSubjects(branch);
  const phaseTitle =
    clampedDay <= 35
      ? 'مرحلة بناء الأساس والفهم العميق'
      : clampedDay <= 70
      ? 'مرحلة حل البكالوريات والتمارين المتنوعة'
      : clampedDay <= 90
      ? 'مرحلة المواضيع الشاملة وتدارك النقائص'
      : 'العد التنازلي النهائي — ليالي الرعد';

  const tasks: StudyTask[] = [];
  for (let slot = 0; slot < 3; slot++) {
    const subj = subjects[(clampedDay * 2 + slot) % subjects.length];
    const topicPool = SYLLABUS_BLOCKS[subj];
    const topicIndex = (Math.floor((clampedDay - 8) / 2) + slot) % topicPool.length;
    const topic = topicPool[topicIndex];

    tasks.push({
      id: `d${clampedDay}-${subj}-${slot}`,
      day: clampedDay,
      subject: subj,
      title: topic,
      xp: slot === 0 ? 55 : 45,
      isSpacedCandidate: subj === 'history' || subj === 'islamic' || subj === 'philosophy' || slot === 0,
    });
  }

  return {
    day: clampedDay,
    title: `اليوم ${String(clampedDay).padStart(2, '0')} — ${phaseTitle}`,
    morningRecallText: 'مراجعة كل ما تم دراسته خلال يوم أمس (قراءة فقط) وبعدها نبدأ في برنامج اليوم.',
    eveningReviewText: 'قبل النوم، قم بمراجعة كل ما تم دراسته خلال اليوم بشكل عام، قراءة تفقدية فقط.',
    tasks,
  };
}

